                ),
              ),

              const SizedBox(height: 12),

              const Text(
                'Halaman detail course yang dibuka '
                'menggunakan Navigator.push().',
                textAlign: TextAlign.center,
              ),

              const SizedBox(height: 30),

              Text(
                'Nama: $studentName',
                textAlign: TextAlign.center,
              ),

              Text(
                'NIM: $studentId',
                textAlign: TextAlign.center,
              ),

              const SizedBox(height: 30),

              ElevatedButton(
                onPressed: () {
